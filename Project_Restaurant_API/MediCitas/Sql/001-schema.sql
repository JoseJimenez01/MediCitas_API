CREATE TABLE IF NOT EXISTS public.reservas (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente varchar(120) NOT NULL,
    fecha date NOT NULL,
    hora time NOT NULL,
    cantidad_personas integer NOT NULL CHECK (cantidad_personas BETWEEN 1 AND 50)
);
CREATE INDEX IF NOT EXISTS "IX_reservas_fecha" ON public.reservas(fecha);

CREATE TABLE IF NOT EXISTS med.clinicas (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    identificador varchar(80) NOT NULL UNIQUE,
    nombre varchar(160) NOT NULL,
    zona_horaria varchar(80) NOT NULL,
    agenda_version bigint NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS med.roles (
    nombre varchar(30) PRIMARY KEY
);
INSERT INTO med.roles VALUES ('platform-admin'), ('clinic-admin'), ('reception'), ('professional') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS med.usuarios (
    id uuid PRIMARY KEY,
    clinica_id uuid REFERENCES med.clinicas(id),
    nombre varchar(160) NOT NULL,
    rol varchar(30) NOT NULL REFERENCES med.roles(nombre),
    activo boolean NOT NULL DEFAULT true,
    UNIQUE (clinica_id, id),
    CHECK ((rol = 'platform-admin') = (clinica_id IS NULL))
);
CREATE TABLE IF NOT EXISTS med.especialidades (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL REFERENCES med.clinicas(id),
    nombre varchar(100) NOT NULL,
    UNIQUE (clinica_id, id),
    UNIQUE (clinica_id, nombre)
);
CREATE TABLE IF NOT EXISTS med.servicios (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL REFERENCES med.clinicas(id),
    nombre varchar(160) NOT NULL,
    duracion_minutos integer NOT NULL CHECK (duracion_minutos BETWEEN 5 AND 480),
    especialidad_id uuid NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    UNIQUE (clinica_id, id),
    FOREIGN KEY (clinica_id, especialidad_id) REFERENCES med.especialidades(clinica_id, id)
);
CREATE TABLE IF NOT EXISTS med.profesionales (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL REFERENCES med.clinicas(id),
    usuario_id uuid NOT NULL,
    especialidad_id uuid NOT NULL,
    nombre varchar(160) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    UNIQUE (clinica_id, id),
    UNIQUE (clinica_id, usuario_id),
    FOREIGN KEY (clinica_id, usuario_id) REFERENCES med.usuarios(clinica_id, id),
    FOREIGN KEY (clinica_id, especialidad_id) REFERENCES med.especialidades(clinica_id, id)
);
CREATE TABLE IF NOT EXISTS med.profesional_servicios (
    clinica_id uuid NOT NULL,
    profesional_id uuid NOT NULL,
    servicio_id uuid NOT NULL,
    PRIMARY KEY (clinica_id, profesional_id, servicio_id),
    FOREIGN KEY (clinica_id, profesional_id) REFERENCES med.profesionales(clinica_id, id),
    FOREIGN KEY (clinica_id, servicio_id) REFERENCES med.servicios(clinica_id, id)
);
CREATE TABLE IF NOT EXISTS med.horarios (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL,
    profesional_id uuid NOT NULL,
    dia_semana integer NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    inicio time NOT NULL,
    fin time NOT NULL,
    CHECK (inicio < fin),
    FOREIGN KEY (clinica_id, profesional_id) REFERENCES med.profesionales(clinica_id, id),
    EXCLUDE USING gist (clinica_id WITH =, profesional_id WITH =, dia_semana WITH =,
        int8range(extract(epoch FROM inicio)::bigint, extract(epoch FROM fin)::bigint, '[)') WITH &&)
);
CREATE TABLE IF NOT EXISTS med.bloqueos (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL,
    profesional_id uuid NOT NULL,
    inicio timestamptz NOT NULL,
    fin timestamptz NOT NULL,
    motivo varchar(300) NOT NULL,
    CHECK (inicio < fin),
    FOREIGN KEY (clinica_id, profesional_id) REFERENCES med.profesionales(clinica_id, id)
);
CREATE INDEX IF NOT EXISTS ix_bloqueos_intervalo ON med.bloqueos USING gist
    (clinica_id, profesional_id, tstzrange(inicio, fin, '[)'));
CREATE TABLE IF NOT EXISTS med.pacientes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL REFERENCES med.clinicas(id),
    identificacion varchar(80) NOT NULL,
    nombre varchar(160) NOT NULL,
    fecha_nacimiento date NOT NULL,
    contacto varchar(300) NOT NULL,
    UNIQUE (clinica_id, id),
    UNIQUE (clinica_id, identificacion)
);
CREATE TABLE IF NOT EXISTS med.citas (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL,
    paciente_id uuid NOT NULL,
    profesional_id uuid NOT NULL,
    servicio_id uuid NOT NULL,
    inicio timestamptz NOT NULL,
    fin timestamptz NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'reservada'
        CHECK (estado IN ('reservada', 'atendida', 'ausente', 'cancelada', 'reprogramada')),
    motivo varchar(300),
    usuario_modificacion uuid NOT NULL,
    anterior_id uuid,
    UNIQUE (clinica_id, id),
    UNIQUE (anterior_id),
    FOREIGN KEY (clinica_id, paciente_id) REFERENCES med.pacientes(clinica_id, id),
    FOREIGN KEY (clinica_id, profesional_id, servicio_id)
        REFERENCES med.profesional_servicios(clinica_id, profesional_id, servicio_id),
    FOREIGN KEY (clinica_id, usuario_modificacion) REFERENCES med.usuarios(clinica_id, id),
    FOREIGN KEY (clinica_id, anterior_id) REFERENCES med.citas(clinica_id, id),
    CHECK (inicio < fin),
    EXCLUDE USING gist (clinica_id WITH =, profesional_id WITH =,
        tstzrange(inicio, fin, '[)') WITH &&) WHERE (estado = 'reservada'),
    EXCLUDE USING gist (clinica_id WITH =, paciente_id WITH =,
        tstzrange(inicio, fin, '[)') WITH &&) WHERE (estado = 'reservada')
);
CREATE INDEX IF NOT EXISTS ix_citas_historial ON med.citas(clinica_id, paciente_id, inicio);
CREATE INDEX IF NOT EXISTS ix_citas_agenda ON med.citas(clinica_id, profesional_id, inicio);
CREATE TABLE IF NOT EXISTS med.notas (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    clinica_id uuid NOT NULL,
    cita_id uuid NOT NULL,
    profesional_id uuid NOT NULL,
    contenido text NOT NULL CHECK (length(btrim(contenido)) BETWEEN 1 AND 20000),
    creada timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (clinica_id, cita_id),
    FOREIGN KEY (clinica_id, cita_id) REFERENCES med.citas(clinica_id, id),
    FOREIGN KEY (clinica_id, profesional_id) REFERENCES med.profesionales(clinica_id, id)
);
CREATE TABLE IF NOT EXISTS med.auditoria (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clinica_id uuid NOT NULL REFERENCES med.clinicas(id),
    paciente_id uuid NOT NULL,
    usuario_id uuid NOT NULL,
    accion varchar(80) NOT NULL,
    recurso_id uuid NOT NULL,
    instante timestamptz NOT NULL,
    payload jsonb NOT NULL,
    anterior text NOT NULL,
    huella text NOT NULL,
    FOREIGN KEY (clinica_id, paciente_id) REFERENCES med.pacientes(clinica_id, id),
    FOREIGN KEY (clinica_id, usuario_id) REFERENCES med.usuarios(clinica_id, id)
);
CREATE INDEX IF NOT EXISTS ix_auditoria_filtros ON med.auditoria(clinica_id, paciente_id, instante);
CREATE INDEX IF NOT EXISTS ix_auditoria_usuario ON med.auditoria(clinica_id, usuario_id, instante);
CREATE TABLE IF NOT EXISTS med.audit_heads (
    clinica_id uuid PRIMARY KEY REFERENCES med.clinicas(id),
    ultimo_id bigint NOT NULL,
    huella text NOT NULL
);

CREATE OR REPLACE FUNCTION med.validar_cita() RETURNS trigger LANGUAGE plpgsql AS $f$
DECLARE duracion integer; zona text; local_inicio timestamp; local_fin timestamp;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF OLD.estado <> 'reservada' THEN RAISE EXCEPTION 'Estado final inmutable' USING ERRCODE = 'P0001'; END IF;
        IF (NEW.clinica_id, NEW.paciente_id, NEW.profesional_id, NEW.servicio_id, NEW.inicio)
            IS DISTINCT FROM (OLD.clinica_id, OLD.paciente_id, OLD.profesional_id, OLD.servicio_id, OLD.inicio) THEN
            RAISE EXCEPTION 'Reprogramar requiere una nueva cita' USING ERRCODE = '23514';
        END IF;
        IF NEW.estado IN ('atendida', 'ausente') AND OLD.inicio > clock_timestamp() THEN
            RAISE EXCEPTION 'La cita aun no inicia' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    SELECT s.duracion_minutos, c.zona_horaria INTO STRICT duracion, zona
    FROM med.servicios s JOIN med.clinicas c ON c.id = s.clinica_id
    JOIN med.profesionales p ON p.clinica_id = s.clinica_id AND p.id = NEW.profesional_id
    WHERE s.clinica_id = NEW.clinica_id AND s.id = NEW.servicio_id;
    NEW.fin := NEW.inicio + make_interval(mins => duracion);
    IF NEW.estado = 'reservada' THEN
        IF NOT EXISTS (SELECT FROM med.servicios WHERE id = NEW.servicio_id AND activo)
            OR NOT EXISTS (SELECT FROM med.profesionales WHERE id = NEW.profesional_id AND activo) THEN
            RAISE EXCEPTION 'Servicio o profesional inactivo' USING ERRCODE = '23514';
        END IF;
        local_inicio := NEW.inicio AT TIME ZONE zona;
        local_fin := NEW.fin AT TIME ZONE zona;
        IF local_inicio::date <> local_fin::date OR NOT EXISTS (
            SELECT FROM med.horarios h WHERE h.clinica_id = NEW.clinica_id
            AND h.profesional_id = NEW.profesional_id AND h.dia_semana = extract(isodow FROM local_inicio)
            AND h.inicio <= local_inicio::time AND h.fin >= local_fin::time
        ) OR EXISTS (
            SELECT FROM med.bloqueos b WHERE b.clinica_id = NEW.clinica_id AND b.profesional_id = NEW.profesional_id
            AND tstzrange(b.inicio, b.fin, '[)') && tstzrange(NEW.inicio, NEW.fin, '[)')
        ) THEN RAISE EXCEPTION 'Espacio fuera de horario o bloqueado' USING ERRCODE = '23514'; END IF;
    END IF;
    RETURN NEW;
END
$f$;
DROP TRIGGER IF EXISTS validar_cita ON med.citas;
CREATE TRIGGER validar_cita BEFORE INSERT OR UPDATE ON med.citas FOR EACH ROW EXECUTE FUNCTION med.validar_cita();

CREATE OR REPLACE FUNCTION med.invalidar_agenda() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = med, pg_temp AS $f$
BEGIN
    UPDATE med.clinicas SET agenda_version = agenda_version + 1 WHERE id = COALESCE(NEW.clinica_id, OLD.clinica_id);
    RETURN COALESCE(NEW, OLD);
END
$f$;
