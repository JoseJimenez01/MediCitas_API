DECLARE tabla text;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['citas', 'horarios', 'bloqueos', 'servicios', 'profesional_servicios', 'profesionales'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS invalidar_agenda ON med.%I', tabla);
        EXECUTE format('CREATE TRIGGER invalidar_agenda AFTER INSERT OR UPDATE OR DELETE ON med.%I FOR EACH ROW EXECUTE FUNCTION med.invalidar_agenda()', tabla);
    END LOOP;
END
$triggers$;

CREATE OR REPLACE FUNCTION med.resolve_identity(sujeto uuid)
RETURNS TABLE(id uuid, clinica_id uuid, rol varchar, activo boolean, profesional_id uuid)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = med, pg_temp AS $f$
    SELECT u.id, u.clinica_id, u.rol, u.activo, p.id FROM med.usuarios u
    LEFT JOIN med.profesionales p ON p.usuario_id = u.id AND p.clinica_id = u.clinica_id AND p.activo
    WHERE u.id = sujeto
$f$;

CREATE OR REPLACE FUNCTION med.auditar(paciente uuid, accion text, recurso uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = med, public, pg_temp AS $f$
DECLARE tenant uuid := nullif(current_setting('app.tenant_id', true), '')::uuid;
actor uuid := nullif(current_setting('app.subject', true), '')::uuid;
prev text; payload jsonb; fingerprint text; entry_id bigint; momento timestamptz := clock_timestamp();
BEGIN
    IF NOT EXISTS (SELECT FROM med.usuarios WHERE id = actor AND clinica_id = tenant AND activo)
        OR NOT EXISTS (SELECT FROM med.pacientes WHERE id = paciente AND clinica_id = tenant) THEN
        RAISE EXCEPTION 'Contexto de auditoria invalido' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(tenant::text, 43));
    SELECT h.huella INTO prev FROM med.audit_heads h WHERE h.clinica_id = tenant;
    prev := COALESCE(prev, '');
    payload := jsonb_build_object('clinica', tenant, 'usuario', actor, 'paciente', paciente,
        'accion', accion, 'recurso', recurso, 'instante', momento);
    fingerprint := encode(digest(prev || payload::text, 'sha256'), 'hex');
    INSERT INTO med.auditoria(clinica_id, paciente_id, usuario_id, accion, recurso_id, instante, payload, anterior, huella)
    VALUES (tenant, paciente, actor, accion, recurso, momento, payload, prev, fingerprint) RETURNING id INTO entry_id;
    INSERT INTO med.audit_heads VALUES (tenant, entry_id, fingerprint)
    ON CONFLICT (clinica_id) DO UPDATE SET ultimo_id = EXCLUDED.ultimo_id, huella = EXCLUDED.huella;
END
$f$;

